"""Curated "Choose from Library" catalog (read side).

The manifest is generated by scripts/library_catalog.py from the curated
folders and uploaded to Cloudflare R2 by scripts/r2_sync.py. This module only
reads it and applies the tier-routing rules.

Source of truth:
  R2 configured (backend/storage/r2.py)  -> library/manifest.json in R2, cached
                                            for R2_MANIFEST_TTL seconds (default 300)
  R2 not configured                      -> data/library/manifest.json (local dev),
                                            re-read when the file changes
"""

from __future__ import annotations

import json
import os
import time
from pathlib import Path

from backend.storage import r2

ROOT = Path(__file__).resolve().parents[2]
LIB_DIR = ROOT / "data" / "library"
MANIFEST = LIB_DIR / "manifest.json"

_cache: dict = {"mtime": None, "data": None}
_r2_cache: dict = {"at": 0.0, "data": None}


class CatalogUnavailable(RuntimeError):
    """The manifest hasn't been generated (run scripts/library_catalog.py build)."""


def _load_r2() -> dict:
    ttl = float(os.environ.get("R2_MANIFEST_TTL", "300"))
    if _r2_cache["data"] is not None and time.monotonic() - _r2_cache["at"] < ttl:
        return _r2_cache["data"]
    try:
        data = json.loads(r2.fetch_bytes(r2.MANIFEST_KEY))
    except Exception as exc:  # noqa: BLE001 - surfaced as 503, never a silent local fallback
        raise CatalogUnavailable(f"Library manifest unavailable from R2 ({type(exc).__name__}: {exc}).") from exc
    _r2_cache.update(at=time.monotonic(), data=data)
    return data


def load() -> dict:
    if r2.configured():
        return _load_r2()
    try:
        mtime = MANIFEST.stat().st_mtime
    except FileNotFoundError as exc:
        raise CatalogUnavailable(
            "Library manifest missing — run `python scripts/library_catalog.py curate` then `build`."
        ) from exc
    if _cache["mtime"] != mtime:
        _cache["data"] = json.loads(MANIFEST.read_text())
        _cache["mtime"] = mtime
    return _cache["data"]


def items() -> list[dict]:
    return load()["items"]


def get(item_id: str) -> dict | None:
    return next((i for i in items() if i["id"] == item_id), None)


def keys(item: dict) -> dict:
    """R2 keys for an item (from the manifest when present, else derived)."""
    return item.get("r2") or r2.library_keys(item)


def image_path(item: dict, kind: str) -> Path:
    folder = {"thumbnail": "thumbnails", "preview": "previews"}[kind]
    return LIB_DIR / folder / item[kind]


def route(item: dict, requested_tier: int | None = None) -> dict:
    """The processing plan for a selected item. The catalog's routing is the
    authority: Sentinel-2 is locked to Tier 1 whatever the UI requests, and a
    tile without georeference can't run DEM-only (there is no location to
    fetch a DEM for)."""
    base = dict(item["routing"])
    notes = []
    tier = base["tier"]
    if requested_tier is not None and requested_tier != tier:
        if base.get("locked"):
            notes.append(
                f"Tier {requested_tier} was requested but this item is locked to Tier {tier}: "
                "height prediction does not work on 10 m Sentinel-2, so it is never attempted."
            )
        elif requested_tier == 1 and not item.get("georeferenced"):
            notes.append(
                "Tier 1 (DEM only) was requested but this tile has no georeference, so no DEM can be "
                f"fetched; it stays on Tier {tier}."
            )
        elif requested_tier == 1:
            # A georeferenced Tier 2 item may be run DEM-only on request.
            tier = 1
            base.update(
                label="Tier 1 — DEM only",
                dem="FABDEM",
                summary="Terrain from FABDEM only (height prediction skipped at the user's request).",
            )
    base["tier"] = tier
    return {"tier": tier, "routing": base, "notes": notes}
